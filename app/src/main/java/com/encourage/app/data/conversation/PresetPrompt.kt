  /** 按分组归类（保持 ALL 的原始顺序，用于列表分区展示）。 */
  fun grouped(): List<Pair<String, List<PresetPrompt>>> {
    val order = mutableListOf<String>()
    val map = LinkedHashMap<String, MutableList<PresetPrompt>>()
    for (p in ALL) {
      if (map[p.category] == null) {
        map[p.category] = mutableListOf()
        order.add(p.category)
      }
      map[p.category]!!.add(p)
    }
    return order.map { it to map[it]!! }
  }

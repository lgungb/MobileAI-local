/*
 * Encourage — 常用提示词预设（对话新建流程）
 *
 * 【功能说明】
 * 「对话」Tab 右下角「+」新建会话时，第一步让用户从一批常用提示词里挑一个作为
 * 这条「特调记录」的角色设定（systemPrompt）。每条提示词都有一个直观的标题，

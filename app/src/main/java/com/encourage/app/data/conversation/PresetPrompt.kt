 * 1. 提示词用中文书写（面向中文用户），内容即「角色设定」，直接作为 systemPrompt 落库；
 * 2. 提供「通用助手」作为默认/兜底项（空提示词 = 走模型默认行为）；
 * 3. 纯静态数据，无外部依赖，便于后续按需增删。
 */

